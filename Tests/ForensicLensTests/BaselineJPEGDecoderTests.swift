    func testDecodesAJPEGFromAnotherEncoder() throws {
        let decoded = try BaselineJPEGDecoder.decode(gdiJPEG)
        XCTAssertEqual(decoded.width, 24)
        XCTAssertEqual(decoded.height, 16)
        var expected: [UInt8] = []
        for y in 0..<16 {
            for x in 0..<24 { expected += [UInt8(40 + 8 * x), UInt8(60 + 10 * y), UInt8(200 - 5 * x - 4 * y)] }
        }
        XCTAssertLessThan(meanAbsoluteDifference(decoded.pixels, expected), 6)
        let expectedBuffer = try PixelBuffer(width: 24, height: 16, channels: 3, pixels: expected)
        let luminance = try BaselineJPEGDecoder.decode(gdiJPEG, output: .luminance)
        XCTAssertLessThan(meanAbsoluteDifference(luminance.pixels, luma(expectedBuffer)), 1.5)
    }

    // MARK: - Failures

    func testNonJPEGIsRejected() {
        XCTAssertThrowsError(try BaselineJPEGDecoder.decode([0x42, 0x4D, 0, 0, 0, 0])) { XCTAssertEqual($0 as? JPEGDecodingError, .notJPEG) }
        XCTAssertThrowsError(try BaselineJPEGDecoder.decode([])) { XCTAssertEqual($0 as? JPEGDecodingError, .notJPEG) }
    }

    func testTruncatedJPEGFailsCleanly() throws {
        let jpeg = TestJPEGEncoder.encode(try pattern(), quality: 90)
        for length in [3, 40, jpeg.count / 2, jpeg.count - 3] {
            XCTAssertThrowsError(try BaselineJPEGDecoder.decode(Array(jpeg.prefix(length))), "length \(length)")
        }
        XCTAssertThrowsError(try BaselineJPEGDecoder.decode(Array(gdiJPEG.prefix(gdiJPEG.count - 40))))
    }

    func testCorruptScanDataFailsCleanly() throws {
        var jpeg = TestJPEGEncoder.encode(try pattern(), quality: 90, restartInterval: 2)
        // Replace a restart marker with a different marker.
        if let index = (2..<(jpeg.count - 1)).first(where: { jpeg[$0] == 0xFF && jpeg[$0 + 1] == 0xD0 }) {
            jpeg[index + 1] = 0xC8
        }
        XCTAssertThrowsError(try BaselineJPEGDecoder.decode(jpeg))
    }

    func testProgressiveJPEGIsUnsupported() {
        // SOI, then a progressive frame header (SOF2) for a 16x16 grayscale image.
        let progressive: [UInt8] = [0xFF, 0xD8, 0xFF, 0xC2, 0x00, 0x0B, 0x08, 0x00, 0x10, 0x00, 0x10, 0x01, 0x01, 0x11, 0x00, 0xFF, 0xD9]
        XCTAssertThrowsError(try BaselineJPEGDecoder.decode(progressive)) { error in
            XCTAssertEqual(error as? JPEGDecodingError, .unsupported("progressive JPEG"))
        }
    }

    func testImageWithoutScanFailsCleanly() {
        XCTAssertThrowsError(try BaselineJPEGDecoder.decode([0xFF, 0xD8, 0xFF, 0xD9]))
    }
