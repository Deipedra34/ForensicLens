import XCTest
import ImageDecoding

/// Covers `BaselineJPEGDecoder`: round trips through the test encoder (4:4:4,
/// 4:2:0 with restart markers, grayscale), a JPEG written by an independent
/// encoder (Windows' GDI+, embedded below), 1/8-scale decoding, and every
/// way a broken or unsupported file must fail cleanly.
final class BaselineJPEGDecoderTests: XCTestCase {
    // MARK: - Helpers

    /// A smooth RGB pattern with edges, at a size that isn't a multiple of
    /// 8 or 16 (so partial blocks and MCUs get exercised).
    private func pattern(width: Int = 70, height: Int = 45) throws -> PixelBuffer {
        var pixels: [UInt8] = []
        for y in 0..<height {
            for x in 0..<width {
                let r = 128 + 100 * sin(Double(x) / 7) * cos(Double(y) / 9)
                let g = (x / 10 + y / 10) % 2 == 1 ? Double(40 + 3 * x) : Double(200 - 2 * y)
                let b = Double(x * 255 / (width - 1))
                pixels += [r, g, b].map { UInt8(clamping: Int($0)) }
            }
        }
        return try PixelBuffer(width: width, height: height, channels: 3, pixels: pixels)
    }

    private func grayscale(_ buffer: PixelBuffer) throws -> PixelBuffer {
        try PixelBuffer(width: buffer.width, height: buffer.height, channels: 1, pixels: (0..<(buffer.width * buffer.height)).map { buffer.pixels[$0 * 3 + 1] })
    }

    private func meanAbsoluteDifference(_ a: [UInt8], _ b: [UInt8]) -> Double {
        Double(zip(a, b).reduce(0) { $0 + abs(Int($1.0) - Int($1.1)) }) / Double(max(1, a.count))
    }

    private func luma(_ buffer: PixelBuffer) -> [UInt8] {
        (0..<(buffer.width * buffer.height)).map { buffer.luma(x: $0 % buffer.width, y: $0 / buffer.width) }
    }

    // MARK: - Round trips

    func testColor444RoundTrip() throws {
        let source = try pattern()
        let decoded = try BaselineJPEGDecoder.decode(TestJPEGEncoder.encode(source, quality: 90))
        XCTAssertEqual(decoded.width, 70)
        XCTAssertEqual(decoded.height, 45)
        XCTAssertEqual(decoded.channels, 3)
        XCTAssertLessThan(meanAbsoluteDifference(decoded.pixels, source.pixels), 4)
    }

    func testSubsampledColorWithRestartMarkersRoundTrip() throws {
        let source = try pattern()
        let jpeg = TestJPEGEncoder.encode(source, quality: 85, subsampled: true, restartInterval: 3)
        let decoded = try BaselineJPEGDecoder.decode(jpeg)
        XCTAssertEqual(decoded.channels, 3)
        XCTAssertLessThan(meanAbsoluteDifference(decoded.pixels, source.pixels), 8, "nearest-neighbor chroma costs some color accuracy")
        let luminance = try BaselineJPEGDecoder.decode(jpeg, output: .luminance)
        XCTAssertEqual(luminance.channels, 1)
        XCTAssertLessThan(meanAbsoluteDifference(luminance.pixels, luma(source)), 3, "luminance isn't subsampled")
    }

    func testGrayscaleRoundTrip() throws {
        let source = try grayscale(pattern())
        let decoded = try BaselineJPEGDecoder.decode(TestJPEGEncoder.encode(source, quality: 90))
        XCTAssertEqual(decoded.channels, 1)
        XCTAssertLessThan(meanAbsoluteDifference(decoded.pixels, source.pixels), 2)
    }

    func testEighthScaleIsTheBlockMeans() throws {
        let source = try pattern()
        let jpeg = TestJPEGEncoder.encode(source, quality: 90, subsampled: true)
        let full = try BaselineJPEGDecoder.decode(jpeg, output: .luminance)
        let eighth = try BaselineJPEGDecoder.decode(jpeg, scale: .eighth, output: .luminance)
        XCTAssertEqual(eighth.width, 9)
        XCTAssertEqual(eighth.height, 6)
        for by in 0..<5 {
            for bx in 0..<8 {
                var sum = 0
                for y in 0..<8 { for x in 0..<8 { sum += Int(full.pixels[(by * 8 + y) * 70 + bx * 8 + x]) } }
                XCTAssertEqual(Double(eighth.pixels[by * 9 + bx]), Double(sum) / 64, accuracy: 1.5, "block (\(bx), \(by))")
            }
        }
    }

    func testFrameInfoReadsOnlyTheHeader() throws {
        let jpeg = TestJPEGEncoder.encode(try pattern(), quality: 90)
        XCTAssertEqual(try BaselineJPEGDecoder.frameInfo(jpeg), BaselineJPEGDecoder.FrameInfo(width: 70, height: 45, components: 3))
    }

